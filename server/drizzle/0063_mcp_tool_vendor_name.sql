-- An action's own name and the name a model may call it by are two facts, and `mcp_tools` held one.
--
-- `name` is this deployment's identifier: half of the `<server_id>/<name>` ref a grant is written
-- against, and the half of `mcp__<server_id>__<name>` a model is offered. The model API accepts a
-- tool name matching `^[a-zA-Z0-9_-]+$` and nothing else.
--
-- Arcade's listing answers `qualified_name` — `Gmail.ListEmails` — and the dot is legal there and
-- illegal in a tool name. With one column that spelling went straight into the offered name, and
-- because a request carries every tool together, ONE granted Arcade action failed the WHOLE model
-- call with `Invalid 'tools[47].name'`. No Arcade action had ever been callable by any model.
--
-- So the vendor's spelling gets its own column and `name` becomes offerable by construction.
--
-- ADDED WITH A DEFAULT, BACKFILLED, THEN STRIPPED OF IT, rather than the bare `ADD COLUMN ... NOT
-- NULL` the generator writes. That form is only correct against an EMPTY table: every deployment
-- holding one recorded action would have the statement refused and the migration stop. The default
-- is scaffolding and not a value — Postgres cannot default a column to another column, so the empty
-- string stands only for the instant between the ADD and the UPDATE below, and `DROP DEFAULT` is
-- what keeps it from becoming the answer for some later insert that forgets this column.
--
-- BACKFILLED TO `name`, WHICH IS CORRECT AND NOT A PLACEHOLDER. Every row that exists when this runs
-- was listed by Composio, an MCP server or the Drive REST transport, and all three publish names
-- that are already offerable — the only non-alphanumeric character in any tool name this
-- deployment has recorded is `_`. For those transports the two spellings are genuinely the same
-- string, which is what the backfill records.
--
-- ARCADE ROWS ARE NOT MIGRATED, THEY ARE RE-LISTED. Their `name` has to LOSE the toolkit prefix, and
-- rewriting it here would leave every grant, skill ref and approval snapshot pointing at a ref that
-- no longer exists — a silent re-pointing of authorization records, which is the one thing a
-- migration must not do by inference. The listing is the authority on what an app publishes, so an
-- administrator presses Refresh and the rows are rebuilt from the vendor with both names recorded.
-- Nothing is lost that the vendor cannot answer again, and no Arcade grant was callable before this
-- commit anyway: there is no working state to preserve.
ALTER TABLE "mcp_tools" ADD COLUMN "vendor_name" text DEFAULT '' NOT NULL;--> statement-breakpoint
UPDATE "mcp_tools" SET "vendor_name" = "name";--> statement-breakpoint
ALTER TABLE "mcp_tools" ALTER COLUMN "vendor_name" DROP DEFAULT;
